// 连续性与节奏 —— 唯一该由代码写死的约束。
//
// 【判据】换一本书、换一个题材、换一种文风，这条是否依然成立？
// 只有答案为"是"的才能进这个文件。凡是涉及"好不好看""该怎么写"的，一律不许进来——
// 那属于审美，审美只能来自本书的范本（见 voiceprint.mjs）。
//
// 【来源与教训】
// 之前写死的是"删套话/段落多长/别抒情/实锚密度"这类审美规则，共约 1500 字符。
// 实测下来它们把网文往纯文学方向拽，作者认可的样章被逐条判为毛病，
// 而且规则越堆越多，模型越守规矩越写不动——「越写越差」就是这么来的。
//
// 参照 codex 的 serial-novel-writer 技能重做。那份技能的第一句是：
//   "Write the requested story first; use continuity machinery to support the fiction
//    rather than letting bookkeeping dominate the prose."
// 它整份文件里关于文风只有一句「向已有章节看齐」，其余全是连续性不变量——
// 这才是机器该管的：机器擅长记账，不擅长审美。

// ——— 文风：只有一句 ———
// 不规定任何具体写法。风格锚定在本书已有的章节与范本上（voicePrint 提供原文）。
export const VOICE_MATCH =
  '文风：长度、强度、视角、用词、类型预期，一律【向本书已有章节与范本看齐】；作者另有要求时以作者为准。';

// ——— 连续性不变量 ———
// 这十条与题材文风无关：写仙侠、写民国、写都市，条条都成立。
export const INVARIANTS = [
  '连续性铁律（违反其中任何一条都是硬伤）：',
  '· 人物不能凭空出现在新地点——要么有足够的行程时间，要么在文里交代转场。',
  '· 【死了就是死了】，除非前文已经铺过诈死的机制。',
  '· 受伤、被囚、昏迷、失踪、正在康复的状态，【一直持续到书里写明它改变为止】。',
  '· 人物【只能依据他合理知道的信息行动】——他不在场、没人告诉他的事，他不知道。',
  '· 兵力、钱粮、武器、爵位、证据、特殊能力，都要有【已经交代过的来源】。',
  '· 重要的同伴、俘虏、信使、证人、追兵，场景转走时【必须交代他们的去向或处置】。',
  '· 关系变化要靠选择和代价挣来：【好感不等于信任，信任不等于永久效忠】。',
  '· 分清【叙述者知道的 / 主角知道的 / 对手知道的 / 读者知道的】，不要互相串。',
  '· 故事尚未给出答案的地方，【保留悬而未决】，不要顺手替它定论。',
  '· 【不要发明故事从没给过的精度】——书里没说具体数目，就别编一个数字出来。',
  '',
  '历史或架空题材可以改变史实，但改变必须【由书里已经写到的因果推出来】；',
  '不得为了让某个结果成立，悄悄改写前面已经写过的事。',
].join('\n');

// ——— 节奏：关于故事推进，不是关于句子 ———
export const PACING = [
  '节奏（关于故事推进）：',
  '· 每一章要【解决或实质改变一个近期问题】，并推进至少一条冲突、关系、调查或战略目标。',
  '· 大的胜利必须有铺垫、代价、阻力和后果，不能白得。',
  '· 【不要为了快，一章把好几条大线一起解决】——那是把后面的牌提前打光。',
  '· 也不要拖：重复的内心戏、冗余的解释、说完什么都没变的对话，都是拖。',
  '· 压力—决定—行动—后果—短暂喘息，按场景需要交替，【不要套死模板】。',
  '· 章末停在一个变了的局面、挣来的揭露、艰难的抉择、新的威胁或情绪转折上。',
].join('\n');

// ——— 输出机制 ———
// 【实测】无范本时 claude 整章用了 133 个半角逗号、只有 2 个全角。
// 这条与文风无关——中文正文一律全角，任何书任何题材都成立，所以放在机制层。
export const OUTPUT_RULES = [
  '· 中文正文一律用【全角标点】（，。！？：；“”‘’），不要出现半角的 , . ! ? : ; 或英文引号。',
  '· 【绝不为凑字数复读】：不重复段落、不重复句式、不原地绕圈。写不动就自然收束。',
  '· 章名与全书已有章名不重复（含意思高度相近的）。',
  '· 只输出正文，不要解释、不要总结、不要作者旁白。',
].join('\n');

// ——— 动笔前的私有约束卡 ———
// 让模型在动笔前先把这些想清楚，但【不要输出】。
// 其中"这一章还不能发生什么"最关键——防的是模型一章把好几个大坑全填了。
export const CONSTRAINT_CARD = [
  '【动笔前先在心里理清下面这些，不要写进正文、不要输出】：',
  '· 开篇的确切时间与地点；',
  '· 每个登场人物：他从哪来、身体状况、立场、以及【他此刻知道什么、不知道什么】；',
  '· 这一章要回答的【当下问题】是什么；',
  '· 这一章要推进的那条冲突或关系；',
  '· 必须带到后面去的事实；',
  '· 【这一章还不能发生的结果】——哪些牌现在还不能打；',
  '· 收尾的钩子。',
].join('\n');

// 组装写作时注入的机制层。这是全部——没有任何一条在规定文字该长什么样。
export function mechanics({ card = true } = {}) {
  return [
    VOICE_MATCH,
    '',
    INVARIANTS,
    '',
    PACING,
    '',
    OUTPUT_RULES,
    card ? '\n' + CONSTRAINT_CARD : '',
  ].filter(Boolean).join('\n');
}

// ——— 写完之后的连续性审计 ———
// 【这是对"多轮打磨"的纠正】原来那一轮让模型挑文笔毛病——那是审美，机器判不好，
// 而且挑出来的意见会把文字往更"正确"也更死板的方向推。
// 改成挑【连续性】毛病：人物状态、行程时间、资源数目、知识边界、有没有超前解决。
// 这些是客观的，机器擅长，而且挑出来的每一条都是真错。
export function auditPrompt({ chapterText, prevTail = '', ledger = '', num }) {
  return [
    `你是连续性审校。下面是刚写好的第 ${num} 章。请只查【连续性与节奏】，不要评价文笔。`,
    '',
    '逐条核对：',
    '1. 开头与上一章结尾接得上吗？时间、地点、在场的人、未完的动作。',
    '2. 每个出现的人物：生死、位置、伤情、立场、【他知不知道这件事】，与已知状态是否一致？',
    '3. 行程时间、时辰、期限、兵力数目、粮草、物品归属，有没有对不上的？',
    '4. 有没有人物凭空出现或凭空消失？俘虏、伤员、护送的人、被留下的人，去向交代了吗？',
    '5. 有没有【超前解决】——把本该留到后面的大线一章填完了？',
    '6. 有没有重复前文已经写过的桥段或解释？',
    '7. 有没有发明书里从没给过的精度（具体数目、具体日期）？',
    '',
    prevTail ? `【上一章结尾】\n${prevTail}\n` : '',
    ledger ? `【已知状态（连续性档案）】\n${ledger.slice(0, 4000)}\n` : '',
    `【本章正文】\n${chapterText}`,
    '',
    '输出：只列【确实有问题】的条目，每条写成：',
    '  · 问题：<原文里的具体一句>｜冲突于：<已知的什么>｜怎么改：<最小改动的建议>',
    '没有问题就只回一个字：无。',
    '不要夸、不要打分、不要评价文笔、不要提出文风上的建议。',
  ].filter(Boolean).join('\n');
}

// 按审计意见修订的指令。强调【最小改动】——审计是修 bug，不是重写。
export function fixPrompt({ notes, num, title }) {
  return [
    `连续性审校给出了下面的问题。请【只修这些问题】，用最小的改动。`,
    '',
    notes,
    '',
    '要求：',
    '1. 【不要重写】——只改有问题的那几句/那几处，其余一字不动。',
    '2. 不要因为"顺手"去调整文风、节奏或分段。',
    '3. 改不动的（需要改前面章节才能圆的）就保留原样，不要硬凑。',
    '',
    `输出改好的完整正文，用分隔符包裹：`,
    `<<<CHAPTER 章号=${num} 标题=${title}>>>`,
    `（完整正文）`,
    `<<<END>>>`,
  ].join('\n');
}
