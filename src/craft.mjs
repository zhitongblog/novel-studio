// 叙事结构规范 —— 治「写得像记叙文」。
//
// 【为什么单独一个模块】
// 原来的 STYLE_GUARD 全是【句子层面】的约束（句长、实锚密度、别用套话）。句子层面再怎么调，
// 也治不了"像记叙文"——因为记叙文和小说的差别根本不在句子，在结构：
//
//     记叙文 = 事件按时间罗列（然后…然后…）＋ 叙述距离恒定 ＋ 场景结束时什么都没变
//     小说   = 场景单元（目标→阻碍→结果比预期更糟）＋ 距离有远近 ＋ 每个场景都有价值翻转
//
// 所以这里给的是【骨架】，不是文风。两者叠加才有用：结构决定"抓不抓人"，文风决定"读着舒不舒服"。
//
// 依据两条：
//   · 通用叙事学：Dwight Swain 的 Scene(目标-冲突-灾难) / Sequel(反应-两难-决定)；
//   · 中文网文/移动端的实际约束：黄金三章、章末钩子、3–5 章一个爽点、段落别超 5 行。

// ——— 章节骨架 ———
export const CHAPTER_ARCH = [
  '【章节骨架（这条最重要，决定读者追不追更）】',
  '把这一章拆成 1–3 个【场景单元】来写，绝不要写成"然后…然后…"的流水账。每个场景单元必须齐三样：',
  '  ① 目标：这个场景开始时，主角【当下就想拿到什么】（具体到一件事：问出一句话、进那道门、把人拖走）。',
  '     不是人生目标，是此刻的目标。读者要能一句话说出他现在想干嘛。',
  '  ② 阻碍：谁/什么挡着。阻碍要【有自己的道理】——对手不是笨蛋，他挡着是因为他也想要东西。',
  '  ③ 结果：【比他预想的更糟或更复杂】。干净利落地达成目标 = 场景死了。',
  '     可以是：拿到了但付出代价 / 拿到了却发现要错了 / 没拿到还暴露了自己。',
  '',
  '【价值翻转（检验场景是否成立的唯一标准）】：每个场景结束时，必须有东西【变了】——',
  '安全→危险、信任→怀疑、占上风→被拿捏、有退路→没退路。',
  '如果一个场景结束时局面和开始时一样，那它就是记叙文，删掉或重写。',
  '',
  '【场景之间的过渡要短】：交代主角的反应（身体的一下）、他面临的两难、他做的决定——三句之内推进到下一个场景。',
  '不要用整段心理活动填过渡，那是拖节奏。',
].join('\n');

// ——— 叙述距离与时间处理 ———
export const NARRATIVE_CAMERA = [
  '【叙述距离要变，别全程中景】：记叙文最典型的特征就是从头到尾一个距离、一个语速。',
  '· 重要的时刻【实拍】：一拍一拍地写，对话逐句、动作逐个，让读者跟着走。',
  '· 不重要的过程【一句压掉】："三天后"、"等他再回到胡同口"、"这事后来没人再提"。',
  '  记叙文的病就是把过场也当正戏写。舍不得压缩，节奏必死。',
  '· 该贴近时钻进他脑子里（一个念头、一个判断），该拉远时给一句冷的旁观。距离的切换本身就是节奏。',
  '【时间不要平推】：场景【晚进早出】——从冲突已经开始的地方切入，在结果刚落地时切走。',
  '不要写他怎么出门、怎么走路、怎么推门进来，除非路上有事发生。',
].join('\n');

// ——— 章末钩子 ———
// 钩子不是"卖关子"，是给读者一个【具体的、迫近的未知】。抽象的悬念（"命运即将改变"）没有力量。
export const HOOK_MENU = [
  '【章末钩子（必须留，且要具体）】：停在下面某一类上，不要停在总结或抒情上——',
  '· 新出现的威胁：门被推开、名字被喊出、刀已经拔了',
  '· 认知反转：他刚发现自己一直搞错了',
  '· 代价落地：赢了，但失去了某样东西，而读者刚意识到那有多重',
  '· 未答的问题：有人问了一句，他没答；或答了半句',
  '· 倒计时收紧：期限、追兵、伤势——某个数字在变小',
  '钩子要【具体可感】，"炸弹还有三分钟"比"危险正在逼近"有力十倍。',
].join('\n');

