// 组合成一份完整的结构规范。write=写新章 / rewrite=重写已有章，措辞略有不同。
export function craftSpec({ mode = 'write' } = {}) {
  return [
    CHAPTER_ARCH,
    '',
    NARRATIVE_CAMERA,
    '',
    HOOK_MENU,
    '',
    MOBILE_READ,
    '',
    mode === 'rewrite'
      ? '【重写时特别注意】：原来那一版最可能的毛病就是"事件罗列、场景没有翻转、结尾在总结"。'
        + '重写时先想清楚这一章有几个场景、每个场景主角要什么、结束时什么变了，再动笔。'
      : '',
  ].filter(Boolean).join('\n');
}

// 开篇章（第 1–3 章）另有硬要求：网文的留存几乎全押在这里。
export const GOLDEN_OPENING = [
  '【这是开篇章，留存全押在这里】：',
  '· 第一句就要有具体的人在具体的处境里做具体的事，不要从天气、回忆、世界观、身世背景开场。',
  '· 三行之内让读者知道：他是谁、他此刻想要什么、什么挡着他。',
  '· 主角的【看家本事】要在本章之内亮一次（哪怕只亮半招），让读者知道跟着他能看到什么。',
  '· 本章之内必须发生一件【不可逆的事】，把他推上这条路——不能只是"介绍"。',
].join('\n');

export function openingSection(num) {
  return (Number(num) > 0 && Number(num) <= 3) ? '\n' + GOLDEN_OPENING + '\n' : '';
}

// ——— 段落呼吸的自动闸 ———
// 光靠提示词约束靠不住：模型已经证明会把"段落要短"推到极端（155 段 / 3307 字）。
// 所以写完之后【真的去量一遍】，太碎就打回让它重排。规则是死的，尺子是活的。
export function paragraphHealth(text) {
  const ps = String(text || '').split('\n').map(x => x.trim()).filter(Boolean);
  if (ps.length < 5) return { ok: true, reason: 'too-short-to-judge' };
  const hz = (x) => (x.match(/[\u4e00-\u9fff]/g) || []).length;
  const lens = ps.map(hz);
  const total = lens.reduce((a, b) => a + b, 0);
  const tiny = lens.filter(x => x <= 10).length;
  const tinyPct = tiny / ps.length;
  const avg = total / ps.length;

  // 最长的一串"连续单行段"——机关枪感主要来自这个，比平均值更能说明问题
  let run = 0, maxRun = 0;
  for (const L of lens) { if (L <= 10) { run++; maxRun = Math.max(maxRun, run); } else run = 0; }

  const problems = [];
  if (tinyPct > 0.35) problems.push(`${Math.round(tinyPct * 100)}% 的段落不到 10 字（健康值 ≤35%）`);
  if (avg < 28) problems.push(`平均段长仅 ${avg.toFixed(0)} 字（健康值 ≥28）`);
  if (maxRun >= 8) problems.push(`有连续 ${maxRun} 段都只有一行（健康值 <8）`);

  return {
    ok: problems.length === 0,
    paras: ps.length, avgLen: +avg.toFixed(1), tinyPct: +(tinyPct * 100).toFixed(0), maxRun,
    problems,
  };
}

// 打回重排的指令。只让它【合并段落】，不许改字——避免"重排"变成又写一遍、把好句子改没了。
export function reflowInstruction(h, num, title) {
  return [
    `这一章的【段落呼吸】不合格，需要重新分段。检测到：`,
    ...h.problems.map(x => '· ' + x),
    ``,
    `请把正文【重新分段】后原样输出：`,
    `1. 把那些连续的单行短段【合并成 2–5 句的段落】——同一个动作序列、同一段描写、同一个人的话与他的动作，应该在一段里。`,
    `2. 只在真正的转折、要害、情绪落点上保留单句成段，【全章最多十来处】。`,
    `3. 【一个字都不要改】：不许增删改写任何文字、不许调整语序，只动换行。`,
    `4. 对话仍是一人一段，但说话人的动作神情要并进他那一段。`,
    ``,
    `输出仍用分隔符包裹：`,
    `<<<CHAPTER 章号=${num} 标题=${title}>>>`,
    `（重新分段后的完整正文）`,
    `<<<END>>>`,
  ].join('\n');
}
